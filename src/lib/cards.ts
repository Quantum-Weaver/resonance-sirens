// KP's correction, 2026-08-17: "simpl cards, emoji to capture the moment."
//
// The first surface was a grid of four hundred symbols. That is the same
// mistake this house names everywhere else — "too much at once gets us off
// track quickly" (his word, the same evening). A tracker opened on a hard day
// must offer a few large, obvious things, not a search problem.
//
// SO: SIX CARDS. Each is one symbol and one press. The whole alphabet is still
// there behind a quiet "another symbol" door, and any symbol she uses becomes
// a card — but the surface she meets is six.
//
// THE OPENING SIX ARE NOT A TAXONOMY. They carry no names, no meanings, no
// light/medium/heavy. They are simply six distinct symbols to start from,
// because a blank surface is not neutrality, it is a locked door. Her own use
// replaces them within days — `hers()` in symbols.ts derives her real cards
// from her own moments and these recede on their own.
//
// KP's ruling of 2026-07-31 governs every one of them, carried in the emoji
// dataset's own header: "Names are for search only - meaning is the vessel's
// own." Nothing in this app will ever tell her what her symbol meant.

